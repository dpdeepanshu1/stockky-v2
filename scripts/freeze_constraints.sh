#!/usr/bin/env bash
# group313: pin every Python dependency (direct AND transitive) to the versions that actually install and pass the tests.
# Writes services/<svc>/constraints.txt; the Dockerfiles use it automatically (pip install -r requirements.txt -c constraints.txt).
# Run ON THE VM (needs docker + network), after the test suites are green, then commit/keep the files:
#   scripts/freeze_constraints.sh            # all services
#   scripts/freeze_constraints.sh real-trade-service position-stocks-service
# Uses the Python version from each Dockerfile and the machine's own architecture (the VM builds the images, so that is what must match).
# To upgrade later: delete a service's constraints.txt, run this again, run the tests, redeploy.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
svcs=("$@"); [ ${#svcs[@]} -gt 0 ] || svcs=(analysis-intelligence-service api-gateway calibration-runner-service decision-prediction-service market-data-service notification-scheduler-service position-stocks-service real-trade-service)
for svc in "${svcs[@]}"; do
  d="$root/services/$svc"
  tag="$(grep -m1 -E '^FROM python:' "$d/Dockerfile" | sed -E 's/^FROM (python:[^ ]+).*/\1/')"
  echo ">> $svc ($tag)"
  tmp="$(mktemp)"
  docker run --rm -v "$d":/app -w /app "$tag" sh -c \
    'pip install -q --root-user-action=ignore -r requirements.txt >&2 && pip freeze --exclude-editable | grep -viE "^(pip|setuptools|wheel)=="' > "$tmp"
  { echo "# generated by scripts/freeze_constraints.sh on $(date -u +%F) with $tag - do not edit by hand"; cat "$tmp"; } > "$d/constraints.txt"
  rm -f "$tmp"; echo "   $(grep -vc '^#' "$d/constraints.txt") pinned"
done
