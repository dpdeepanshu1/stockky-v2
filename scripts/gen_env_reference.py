#!/usr/bin/env python3
"""gen_env_reference.py - one table of every environment variable the services read, so none is documented nowhere.

The code reads ~600 variables through os.getenv / os.environ.get (tuning knobs, kill switches, thresholds). Most were
only explained in the session note that added them. This scans the production code (not tests) with the AST and writes
docs/ENV_REFERENCE.md: variable, services that read it, the default found in the code, and where it is read.

  python3 scripts/gen_env_reference.py            # (re)write docs/ENV_REFERENCE.md
  python3 scripts/gen_env_reference.py --check    # exit 1 when the file is out of date (for CI / before a deploy)

Defaults are read from `os.getenv("X", "d")` and from the `(os.getenv("X") or "").strip() or "d"` form; anything else is
shown as `(dynamic)`. A variable listed here is READ by the code; whether it is SET is decided by your .env / compose file.
"""
from __future__ import annotations

import ast
import os
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "ENV_REFERENCE.md"
SKIP = {"tests", "__pycache__", "node_modules", "scripts", ".git"}
CALLS = {"os.getenv", "os.environ.get", "_os.getenv", "_os.environ.get", "environ.get", "getenv"}


def _const(node):
    if isinstance(node, ast.Constant):
        return node.value
    return None


def scan():
    found = defaultdict(lambda: {"svc": set(), "defaults": [], "where": []})
    for dp, dn, fn in os.walk(ROOT / "services"):
        dn[:] = sorted(d for d in dn if d not in SKIP)
        for f in sorted(fn):
            if not f.endswith(".py"):
                continue
            p = Path(dp) / f
            try:
                tree = ast.parse(p.read_text(encoding="utf-8"))
            except (SyntaxError, UnicodeDecodeError):
                continue
            parents = {}
            for n in ast.walk(tree):
                for c in ast.iter_child_nodes(n):
                    parents[c] = n
            rel = p.relative_to(ROOT).as_posix()
            svc = rel.split("/")[1]
            for n in ast.walk(tree):
                if not (isinstance(n, ast.Call) and ast.unparse(n.func) in CALLS and n.args):
                    continue
                name = _const(n.args[0])
                if not isinstance(name, str) or not name.isupper():
                    continue
                default = None
                if len(n.args) > 1:
                    default = _const(n.args[1])
                else:
                    # (os.getenv("X") or "").strip() or "d"  -> default "d"
                    cur = n
                    for _ in range(4):
                        cur = parents.get(cur)
                        if cur is None:
                            break
                        if isinstance(cur, ast.BoolOp) and isinstance(cur.op, ast.Or):
                            consts = [_const(v) for v in cur.values if isinstance(v, ast.Constant) and v.value not in ("", None)]
                            if consts:
                                default = consts[-1]
                            break
                e = found[name]
                e["svc"].add(svc)
                e["defaults"].append("(dynamic)" if default is None and len(n.args) > 1 else ("" if default is None else repr(default)))
                if len(e["where"]) < 3:
                    e["where"].append(f"{rel}:{n.lineno}")
    return found


def render(found) -> str:
    lines = [
        "# Environment variable reference",
        "",
        "Generated by `python3 scripts/gen_env_reference.py` - do not edit by hand (run it again after adding a variable).",
        f"{len(found)} variables are read by the production code. `Default` is what the code uses when the variable is unset;",
        "`(dynamic)` means the default is computed, `-` means no default is given at the read site.",
        "",
        "| Variable | Services | Default | First read at |",
        "|---|---|---|---|",
    ]
    for name in sorted(found):
        e = found[name]
        defaults = sorted({d for d in e["defaults"] if d}) or ["-"]
        d = ", ".join(defaults[:2]).replace("|", "\\|")
        if len(d) > 60:
            d = d[:57] + "..."
        lines.append(f"| `{name}` | {', '.join(sorted(e['svc']))} | {d} | `{e['where'][0]}` |")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render(scan())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/ENV_REFERENCE.md is out of date - run: python3 scripts/gen_env_reference.py")
            return 1
        print("docs/ENV_REFERENCE.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count(chr(10)) - 8} variables")
    return 0


if __name__ == "__main__":
    sys.exit(main())
