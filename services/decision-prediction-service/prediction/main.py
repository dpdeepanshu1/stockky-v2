"""
Prediction Service — XGBoost probability model + Groq-generated explanation.

Two genuinely separate things happen here, worth keeping distinct in your
head (and in any future accuracy work):

1. `prediction_score` — the actual predictive signal. Comes entirely from
   the trained XGBoost classifier (see train.py) scoring 11 technical
   features. This is what decision-engine-service actually weighs into
   the BUY/SELL decision. Nothing about the LLM below changes this number.

2. `note` — a plain-English explanation of that score, generated by an LLM
   (Groq) purely for readability. It does NOT feed back into the score.
   If you want the LLM to genuinely influence accuracy, it would need to
   produce a structured signal (e.g. a catalyst score from news/events)
   that decision-engine-service incorporates as its own input — that's a
   bigger change than what's here today.

Groq (API-based) is the right call for a 512MB Render instance: there is
no version of a locally-hosted LLM that fits in that budget, let alone
runs fast enough for a live request. An API call adds negligible memory
overhead regardless of which model Groq serves it from.
"""
import os
import logging

import httpx
import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pred_features import latest_feature_vector, FEATURE_COLUMNS

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("prediction-service")

# Trailing slashes are a classic footgun here: os.getenv(...) + "/history/..."
# silently produces a DOUBLE slash if the env var itself ends in "/", and
# that double slash gets collapsed by some HTTP clients into a request for
# the wrong path entirely (confirmed: "//history/TCS" became a request for
# "/TCS", not "/history/TCS" — a 404 that looked like a routing bug because
# it was one). Stripping it defensively means this can't happen regardless
# of how the env var gets set on Render.
MARKET_DATA_URL = os.getenv("MARKET_DATA_URL", "https://market-data-service-r6d7.onrender.com").rstrip("/")
MODEL_PATH = os.getenv("MODEL_PATH", "model.pkl")

# llama-3.1-8b-instant was deprecated by Groq on 2026-06-17 with a shutdown
# date of 2026-08-16 — openai/gpt-oss-20b is Groq's own recommended direct
# replacement (same speed/cost class, free-tier friendly). Override via env
# var if you want to try a different model without a redeploy.
GROQ_MODEL = os.getenv("GROQ_MODEL", "openai/gpt-oss-20b")

GROQ_API_KEY = os.getenv("GROQ_API_KEY")
if GROQ_API_KEY:
    GROQ_API_KEY = GROQ_API_KEY.strip()
    logger.info(f"Groq key loaded (starts with: {GROQ_API_KEY[:8]}...), model={GROQ_MODEL}")
else:
    logger.warning("Groq key is missing — will try Gemini, then the plain-number fallback")

# Second, independent provider. The point isn't that Gemini is "better" —
# it's that Groq and Gemini deprecating/rate-limiting/going down at the
# same time is astronomically unlikely, so this is what actually makes
# note-generation resilient instead of just moving the single-point-of-
# failure to a different vendor. Check ai.google.dev/gemini-api/docs/models
# for the current recommended free-tier model if this one gets retired —
# Google rotates these roughly as often as Groq does.
GEMINI_MODEL = os.getenv("GEMINI_MODEL", "gemini-3.6-flash")
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")
if GEMINI_API_KEY:
    GEMINI_API_KEY = GEMINI_API_KEY.strip()
    logger.info(f"Gemini key loaded (starts with: {GEMINI_API_KEY[:8]}...), model={GEMINI_MODEL}")
else:
    logger.warning("Gemini key is missing — no fallback provider if Groq fails")

app = FastAPI(title="Stockky Prediction Service", version="0.6.1")
app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["*"], allow_headers=["*"])

_model = None
if os.path.exists(MODEL_PATH):
    try:
        _model = joblib.load(MODEL_PATH)
        logger.info("Loaded trained model from %s", MODEL_PATH)
    except Exception as e:
        logger.error("Failed to load model: %s", e)
else:
    logger.warning("No trained model found — using fallback")


@app.get("/")
async def root():
    return {"service": "Stockky Prediction Service", "version": "0.6.1", "status": "running"}


@app.get("/health")
def health():
    return {"status": "ok", "service": "prediction-service", "model_loaded": _model is not None}


def _fetch_history(symbol: str) -> pd.DataFrame:
    try:
        # 45s, not 15s: market-data-service now retries against Yahoo's
        # rate limiter with real patience — a short timeout here would cut
        # that off before it has a chance to help, which matters most for
        # a symbol being fetched for the very first time (nothing cached).
        resp = httpx.get(f"{MARKET_DATA_URL}/history/{symbol}", params={"period": "1y"}, timeout=45)
        resp.raise_for_status()
        data = resp.json()
    except httpx.HTTPError as e:
        raise HTTPException(status_code=502, detail=f"Market data unreachable: {e}")

    candles = data.get("candles", [])
    if len(candles) < 210:
        raise HTTPException(
            status_code=422,
            detail=(
                f"Only {len(candles)} trading days of history available; need at least 210 "
                "for a stable prediction (EMA200 needs that much runway). This is expected "
                "for a recently listed stock, not a bug — it'll start working once enough "
                "history has accumulated."
            ),
        )
    df = pd.DataFrame(candles)
    df["date"] = pd.to_datetime(df["date"])
    df.set_index("date", inplace=True)
    df.rename(columns=str.title, inplace=True)
    return df


def _describe_feature(features: dict, key: str, fmt: str = "{:.1f}", default="n/a") -> str:
    val = features.get(key)
    return fmt.format(val) if val is not None else default


def _call_groq(system_prompt: str, user_prompt: str) -> str | None:
    """Returns the note text, or None on any failure (never raises) so the
    caller can move on to the next provider."""
    if not GROQ_API_KEY:
        return None
    try:
        resp = httpx.post(
            "https://api.groq.com/openai/v1/chat/completions",
            json={
                "model": GROQ_MODEL,
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                "temperature": 0.4,
                "max_tokens": 100,  # Reduced from 350 to save tokens
            },
            headers={
                "Authorization": f"Bearer {GROQ_API_KEY}",
                "Content-Type": "application/json",
            },
            timeout=20,
        )
        if resp.status_code == 200:
            note = resp.json()["choices"][0]["message"]["content"].strip()
            return note or None
        logger.warning(f"Groq returned {resp.status_code}: {resp.text[:300]}")
        return None
    except Exception as e:
        logger.warning(f"Groq call failed: {repr(e)}")
        return None


def _call_gemini(system_prompt: str, user_prompt: str) -> str | None:
    """Same contract as _call_groq: note text, or None on failure."""
    if not GEMINI_API_KEY:
        return None
    try:
        resp = httpx.post(
            f"https://generativelanguage.googleapis.com/v1beta/models/{GEMINI_MODEL}:generateContent",
            json={
                "system_instruction": {"parts": [{"text": system_prompt}]},
                "contents": [{"parts": [{"text": user_prompt}]}],
                "generationConfig": {"temperature": 0.4, "maxOutputTokens": 100},  # Reduced
            },
            headers={"x-goog-api-key": GEMINI_API_KEY, "Content-Type": "application/json"},
            timeout=20,
        )
        if resp.status_code == 200:
            data = resp.json()
            note = data["candidates"][0]["content"]["parts"][0]["text"].strip()
            return note or None
        logger.warning(f"Gemini returned {resp.status_code}: {resp.text[:300]}")
        return None
    except Exception as e:
        logger.warning(f"Gemini call failed: {repr(e)}")
        return None


def _generate_llm_note(features: dict, probability: float, symbol: str) -> str:
    fallback = f"Estimated {round(probability * 100)}% probability of a ~5%+ move within 10 trading days."

    # These are the ACTUAL keys latest_feature_vector() produces (see
    # features.py — FEATURE_COLUMNS). An earlier version of this prompt
    # read keys ('rsi', 'adx', 'price_vs_200ema') that don't exist in this
    # dict at all, so it silently fell back to hardcoded defaults (RSI=50,
    # ADX=20, "below 200 EMA") on every single call, for every symbol —
    # the LLM was never actually looking at real data.
    rsi = _describe_feature(features, "rsi_14")
    adx = _describe_feature(features, "adx_14")
    macd_hist = _describe_feature(features, "macd_hist", "{:.2f}")
    close_vs_ema20 = features.get("close_over_ema20")
    ema20_vs_ema50 = features.get("ema20_over_ema50")
    ema50_vs_ema200 = features.get("ema50_over_ema200")
    vol_ratio = _describe_feature(features, "volume_ratio_20", "{:.2f}")
    bb_pct = _describe_feature(features, "bb_pct", "{:.1f}")
    dist_high = _describe_feature(features, "dist_from_20d_high_pct", "{:.1f}")
    dist_low = _describe_feature(features, "dist_from_20d_low_pct", "{:.1f}")
    atr_pct = _describe_feature(features, "atr_pct", "{:.1f}")
    golden_cross = features.get("golden_cross", 0)

    trend_desc = "above" if (ema50_vs_ema200 or 0) > 1 else "below"
    price_desc = "above" if (close_vs_ema20 or 0) > 1 else "below"
    momentum_desc = "strengthening" if (ema20_vs_ema50 or 0) > 1 else "weakening"
    golden_cross_desc = "Yes" if golden_cross == 1 else "No"

    # 🟢 NEW: Single concise sentence prompt
    system_prompt = (
        "You are a concise stock analyst. Given the technical readings, "
        "explain in exactly one clear, accurate sentence why the model estimates the probability it does. "
        "No disclaimers, no jargon dump."
    )
    user_prompt = (
        f"{symbol}: RSI={rsi}, ADX={adx}, MACD hist={macd_hist}, Price {price_desc} 20 EMA, "
        f"momentum {momentum_desc}, trend {trend_desc}, volume={vol_ratio}x avg, golden cross={golden_cross_desc}. "
        f"Model says {round(probability * 100)}% chance of +5% in 10 days. Explain in one sentence."
    )

    # Try Gemini first, then Groq, then fallback.
    for call in (_call_gemini, _call_groq):
        note = call(system_prompt, user_prompt)
        if note:
            return note

    return fallback


# --------------------- Feature alignment ---------------------
def _align_features(features: dict, model) -> dict:
    """Return only the features that the model was trained on."""
    if hasattr(model, 'feature_names_in_'):
        expected = model.feature_names_in_
        aligned = {col: features[col] for col in expected if col in features}
        if len(aligned) != len(expected):
            missing = [col for col in expected if col not in aligned]
            logger.warning(f"Missing features: {missing}")
        return aligned
    return features


@app.get("/predict/{symbol}")
def predict(symbol: str):
    # 🛡️ Robust error handling – never return 502 or 500
    try:
        if _model is None:
            return {
                "symbol": symbol.upper(),
                "model_loaded": False,
                "probability": None,
                "prediction_score": None,
                "note": "No trained model yet.",
            }
        df = _fetch_history(symbol)
        features = latest_feature_vector(df)
        missing = [c for c in FEATURE_COLUMNS if c not in features]
        if missing:
            logger.warning(f"Missing features: {missing}")

        aligned = _align_features(features, _model)
        X = pd.DataFrame([aligned])
        if hasattr(_model, 'feature_names_in_'):
            X = X[_model.feature_names_in_]

        probability = float(_model.predict_proba(X)[0, 1])
        prediction_score = round(probability * 100)
        llm_note = _generate_llm_note(features, probability, symbol)
        return {
            "symbol": symbol.upper(),
            "model_loaded": True,
            "probability": round(probability, 3),
            "prediction_score": prediction_score,
            "note": llm_note,
        }
    except Exception as e:
        # Always 200 with neutral fallback so a single cold-start 502 does not break the scan.
        msg = str(e)
        if "502" in msg or "unreachable" in msg.lower() or "timeout" in msg.lower():
            logger.warning("Prediction skipped for %s (market-data cold/unavailable): %s", symbol, msg[:160])
        elif "422" in msg or "need at least" in msg.lower():
            logger.info("Prediction skipped for %s (insufficient history): %s", symbol, msg[:120])
        else:
            logger.error("Prediction failed for %s: %s", symbol, msg, exc_info=True)
        return {
            "symbol": symbol.upper(),
            "model_loaded": _model is not None,
            "probability": None,
            "prediction_score": 50,
            "note": "AI prediction temporarily unavailable (data service busy or insufficient history). Neutral score used.",
        }


