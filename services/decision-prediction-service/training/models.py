def init_db(engine=None):
    """Create all Stockky training/trades tables if missing (safe to call repeatedly).

    Cheap path: if paper_trades already exists, no-op (no log spam, no DDL).
    """
    global _INIT_DONE, _INIT_LOCK
    import logging
    import threading
    from sqlalchemy import inspect as sa_inspect
    _log = logging.getLogger("training-db")
    if _INIT_DONE:
        return True
    if _INIT_LOCK is None:
        _INIT_LOCK = threading.Lock()
    with _INIT_LOCK:
        if _INIT_DONE:
            return True
        eng = engine or get_engine()
        try:
            insp = sa_inspect(eng)
            if insp.has_table("paper_trades") and insp.has_table("portfolio_account"):
                # Tables already exist — but on Oracle they may predate the
                # IDENTITY fix and still have a bare NUMBER id with no generator,
                # which makes every INSERT fail with ORA-01400. Repair in place
                # before taking the cheap exit. No-op on Postgres.
                ensure_oracle_identity(eng)
                _INIT_DONE = True
                return True
            Base.metadata.create_all(eng)
            ensure_schema(eng)
            ensure_oracle_identity(eng)
            _INIT_DONE = True
            _log.info("init_db: schema created/verified")
            return True
        except Exception as e:
            _log.error("init_db failed: %s", e)
            return False

