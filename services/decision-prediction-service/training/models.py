# Presence of ORACLE_DSN is the single switch that means "this process talks to
# Oracle Autonomous DB" — the same convention used by oracle_compat.py and
# get_engine() below. Evaluated at import time; docker compose always exports it
# before the app starts.
_ORACLE_MODE = bool(_os.environ.get("ORACLE_DSN"))


def _pk_column():
    """An auto-generating integer primary key that works on BOTH backends.

    Why this exists
    ---------------
    ``Column(Integer, primary_key=True, autoincrement=True)`` renders as
    ``SERIAL`` on Postgres (the database generates the value), but on Oracle
    SQLAlchemy renders only a bare ``NUMBER NOT NULL`` — Oracle has no implicit
    auto-increment. Because SQLAlchemy then *omits* ``id`` from the INSERT column
    list and expects the database to fill it, Oracle received NULL and raised::

        ORA-01400: cannot insert NULL into ("ADMIN"."PREDICTION_SNAPSHOTS"."ID")

    That is why Manual trade, Deposit and Training all failed on the Oracle VM
    while working fine on Render.

    What it does
    ------------
    * On **Oracle** (ORACLE_DSN set): renders
      ``GENERATED BY DEFAULT AS IDENTITY``. "BY DEFAULT" (never "ALWAYS") is
      deliberate — ``trades.py`` inserts the singleton ``PortfolioAccount(id=1)``
      explicitly, and ALWAYS would reject that with ORA-32795.
    * On **Render/Neon Postgres** (ORACLE_DSN empty): returns the original
      column definition unchanged, so the emitted DDL stays byte-for-byte
      identical to before. Zero regression risk on the Postgres side.
    """
    if _ORACLE_MODE:
        return Column(Integer, Identity(always=False, start=1, increment=1), primary_key=True)
    return Column(Integer, primary_key=True, autoincrement=True)


# ---------- Portable JSON column (Neon/Postgres  AND  Oracle Autonomous DB) ----------
class PortableJSON(TypeDecorator):
    """A JSON column that renders valid DDL on Postgres *and* Oracle.

    Why this exists
    ---------------
    SQLAlchemy's Oracle dialect cannot render the generic ``JSON`` type as DDL —
    Oracle only gained a native ``JSON`` datatype in 21c, so on an Autonomous DB
    the compiler raises::

        UnsupportedCompilationError: Compiler <OracleTypeCompiler ...>
        can't render element of type JSON

    That single DDL-compilation failure aborted ``Base.metadata.create_all()``
    on the Oracle VM, which meant *none* of the training tables were ever
    created, which in turn made every later query fail with
    ``ORA-00942: table or view does not exist`` (portfolio, paper_trades,
    prediction_snapshots, ...).

    What it does
    ------------
    * On **Oracle**: stores the value as ``CLOB`` text and (de)serialises it
      with ``json.dumps`` / ``json.loads``.
    * On **every other dialect** (Neon/Postgres on Render, SQLite locally):
      resolves to the exact same generic ``JSON`` implementation as before and
      passes values through untouched — so the Render DDL and behaviour are
      byte-for-byte unchanged. Zero regression risk on the Postgres side.
    """

    impl = JSON
    cache_ok = True

    def load_dialect_impl(self, dialect):
        # This is what the DDL compiler renders, and what supplies the
        # bind/result processors at runtime.
        if dialect.name == "oracle":
            return dialect.type_descriptor(Text())
        return dialect.type_descriptor(JSON())

    def process_bind_param(self, value, dialect):
        # Postgres/SQLite: leave the value alone — the native JSON impl below
        # serialises it exactly as it always did.
        if dialect.name != "oracle":
            return value
        if value is None:
            return None
        if isinstance(value, str):
            return value  # already-serialised JSON text
        try:
            return _json.dumps(value, default=str)
        except (TypeError, ValueError):
            return _json.dumps(str(value))

    def process_result_value(self, value, dialect):
        if dialect.name != "oracle":
            return value
        if value is None:
            return None
        if isinstance(value, (bytes, bytearray)):
            try:
                value = value.decode("utf-8")
            except Exception:
                return None
        if not isinstance(value, str):
            return value
        if value.strip() == "":
            return None
        try:
            return _json.loads(value)
        except (TypeError, ValueError):
            return None


# ---------- Numpy conversion helper ----------
def convert_numpy_nan_safe(obj):
    """Recursively convert numpy + strip NaN/Inf for JSON (IREDA etc.)."""
    import math
    try:
        import numpy as np
    except ImportError:
        np = None
    if obj is None:
        return None
    if isinstance(obj, float):
        if math.isnan(obj) or math.isinf(obj):
            return None
        return obj
    if np is not None:
        if isinstance(obj, (np.floating,)):
            f = float(obj)
            return None if (math.isnan(f) or math.isinf(f)) else f
        if isinstance(obj, (np.integer,)):
            return int(obj)
        if isinstance(obj, np.ndarray):
            return [convert_numpy_nan_safe(x) for x in obj.tolist()]
    if isinstance(obj, dict):
        return {k: convert_numpy_nan_safe(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [convert_numpy_nan_safe(v) for v in obj]
    return obj


def convert_numpy(obj):
    """Recursively convert numpy types to Python native types."""
    if isinstance(obj, np.integer):
        return int(obj)
    if isinstance(obj, np.floating):
        return float(obj)
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    if isinstance(obj, dict):
        return {k: convert_numpy(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [convert_numpy(v) for v in obj]
    if isinstance(obj, (np.bool_, bool)):
        return bool(obj)
    return obj

