# Every table whose primary key is the generated integer `id`.
_PK_TABLES = (
    "prediction_snapshots",
    "prediction_outcomes",
    "portfolio_account",
    "portfolio_transactions",
    "paper_trades",
    "trade_backups",
    "training_runs",
    "model_artifacts",
)


def ensure_oracle_identity(engine) -> None:
    """Attach an IDENTITY generator to `id` on Oracle tables that lack one.

    ``_pk_column()`` fixes tables created from now on, but the Oracle VM already
    created these tables during an earlier deploy — with a bare ``NUMBER`` id and
    no generator. ``create_all()`` never alters an existing table, so without
    this repair every INSERT would keep failing with ORA-01400.

    Idempotent and self-healing:
      * skips any table that does not exist yet,
      * skips any id that already has an identity (``user_tab_identity_cols``),
      * starts the sequence at ``MAX(id) + 1`` so existing rows keep their ids
        and no PK collision is possible,
      * uses ``BY DEFAULT`` so explicit inserts (``PortfolioAccount(id=1)``)
        still work,
      * logs and continues on failure rather than blocking startup.

    On Postgres/SQLite this returns immediately, so Render is untouched.
    """
    import logging

    _log = logging.getLogger("training-db")
    try:
        if engine.dialect.name != "oracle":
            return
    except Exception:
        return

    for table in _PK_TABLES:
        tbl = table.upper()  # SQLAlchemy creates unquoted names -> stored uppercase
        try:
            with engine.connect() as conn:
                if not conn.execute(
                    text("SELECT COUNT(*) FROM user_tables WHERE table_name = :t"),
                    {"t": tbl},
                ).scalar():
                    continue
                if conn.execute(
                    text(
                        "SELECT COUNT(*) FROM user_tab_identity_cols "
                        "WHERE table_name = :t AND column_name = 'ID'"
                    ),
                    {"t": tbl},
                ).scalar():
                    continue  # already repaired on an earlier boot
                start_at = int(
                    conn.execute(text(f"SELECT NVL(MAX(id), 0) + 1 FROM {tbl}")).scalar() or 1
                )

            # Oracle accepts the MODIFY with or without a restated datatype
            # depending on version; try the bare form first, then the explicit one.
            variants = (
                f"ALTER TABLE {tbl} MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH {start_at}))",
                f"ALTER TABLE {tbl} MODIFY (id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH {start_at}))",
            )
            last_err = None
            for sql in variants:
                try:
                    with engine.begin() as conn:
                        conn.execute(text(sql))
                    last_err = None
                    break
                except Exception as e:  # noqa: BLE001
                    last_err = e
            if last_err is not None:
                raise last_err

            _log.info(
                "ensure_oracle_identity: %s.id -> GENERATED BY DEFAULT AS IDENTITY (start=%s)",
                tbl,
                start_at,
            )
        except Exception as e:  # noqa: BLE001
            _log.warning("ensure_oracle_identity(%s) skipped: %s", tbl, str(e)[:200])


