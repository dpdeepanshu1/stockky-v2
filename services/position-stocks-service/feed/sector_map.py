def _build() -> Dict[str, str]:
    out: Dict[str, str] = {}
    for sector, names in _SECTORS.items():
        for sym in names.split():
            out.setdefault(sym, sector)
    return out


_BASE = _build()


def _extra() -> Dict[str, str]:
    out: Dict[str, str] = {}
    for part in (os.getenv("BOARD_SECTOR_EXTRA") or "").split(","):
        if "=" in part:
            k, v = part.split("=", 1)
            if k.strip() and v.strip():
                out[k.strip().upper()] = v.strip()
    return out


def sector_of(symbol: str) -> str:
    s = str(symbol or "").upper().replace(".NS", "").replace(".BO", "").strip()
    return _extra().get(s) or _BASE.get(s) or "Other"


def sectors() -> List[str]:
    return sorted(set(_BASE.values()) | set(_extra().values()))


def coverage(symbols) -> float:
    syms = list(symbols)
    if not syms:
        return 0.0
    return sum(1 for s in syms if sector_of(s) != "Other") / len(syms)
