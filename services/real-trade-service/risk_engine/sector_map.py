def _build() -> Dict[str, str]:
    out: Dict[str, str] = {}
    for table in (_SECTORS, _SECTORS_MORE):
        for sector, names in table.items():
            for sym in names.split():
                out.setdefault(sym, sector)
    return out


_BASE = _build()


def _extra() -> Dict[str, str]:
    out: Dict[str, str] = {}
    for part in (os.getenv("BOARD_SECTOR_EXTRA") or "").split(","):
        if "=" in part:
            k, v = part.split("=", 1)
            if k.strip() and v.strip():
                out[k.strip().upper()] = v.strip()
    return out


def sector_of(symbol: str) -> str:
    s = str(symbol or "").upper().replace(".NS", "").replace(".BO", "").strip()
    return _extra().get(s) or _BASE.get(s) or "Other"


def sectors() -> List[str]:
    return sorted(set(_BASE.values()) | set(_extra().values()))


def coverage(symbols) -> float:
    syms = list(symbols)
    if not syms:
        return 0.0
    return sum(1 for s in syms if sector_of(s) != "Other") / len(syms)


def coverage_report(symbols, turnover_fn=None, top: int = 15) -> dict:
    """group311: how much of what the bar store tracks is classified, and which unclassified symbols trade the most (extend those with
    BOARD_SECTOR_EXTRA). `turnover_fn(symbol) -> number` orders the list."""
    syms = list(symbols or [])
    other = [x for x in syms if sector_of(x) == "Other"]
    if turnover_fn is not None:
        try:
            other.sort(key=lambda x: float(turnover_fn(x) or 0.0), reverse=True)
        except Exception:  # noqa: BLE001
            pass
    n = len(syms)
    return {"tracked": n, "classified": n - len(other), "pct": round((n - len(other)) / n * 100.0, 1) if n else None,
            "top_other": other[:top], "mapped_names": len(_BASE)}
